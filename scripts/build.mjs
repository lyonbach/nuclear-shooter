import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Small, dependency-free packager for this game's four ordered source modules.
// The checked-in output also works over file:// and on GitHub Pages.
const root=new URL('../',import.meta.url);
const files=['core.js','audio.js','renderer.js','game.js'];
const modules=[];
for(const file of files){
  const source=(await readFile(new URL(file,root),'utf8'))
    .replace(/^import .*;\n/gm,'')
    .replace(/^export (?=(?:const|function|class)\b)/gm,'');
  if(/^\s*(?:import|export)\s/m.test(source))throw new Error(`Unsupported module syntax in ${file}`);
  modules.push(`// ${file}\n${source}`);
}
const output=`// Generated by scripts/build.mjs. Edit the source modules, then rebuild.\n(()=>{\n'use strict';\n${modules.join('\n')}\n})();\n`;
await writeFile(new URL('blackout.js',root),output);
console.log(`Built ${fileURLToPath(new URL('blackout.js',root))} (${Buffer.byteLength(output)} bytes)`);
